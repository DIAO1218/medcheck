"""Generate the DDI fixture corpus from the pinned table.

Why generated: hand-typing 100 pairs invites transcription errors that look like
matcher bugs. Why committed: the corpus must be frozen so a table edit shows up
as a failing test rather than silently regenerating a green result.

    python scripts/build_ddi_fixtures.py            # write fixtures
    python scripts/build_ddi_fixtures.py --check    # fail if fixtures are stale
"""

from __future__ import annotations

import argparse
import sys
from itertools import combinations
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from medcheck.rules.loader import get_tables

FIXTURE = ROOT / "test" / "fixtures" / "ddi_pairs.yaml"
NEGATIVES = 60


def build() -> dict:
    tables = get_tables()
    drugs = sorted(tables.drugs)

    positives = [
        {
            "pair": sorted(row["pair"]),
            "rule_id": row["rule_id"],
            "severity": row["severity"],
        }
        for row in tables.interactions
    ]
    positives.sort(key=lambda item: item["pair"])

    negatives = []
    for first, second in combinations(drugs, 2):
        if tables.covers_pair(first, second):
            continue
        if tables.is_hole(first, second):
            continue
        negatives.append([first, second])
        if len(negatives) == NEGATIVES:
            break

    holes = [{"pair": sorted(hole)} for hole in (sorted(sorted(h) for h in tables.holes))]
    holes.sort(key=lambda item: item["pair"])

    return {
        "table_version": tables.version,
        "note": (
            "GENERATED by scripts/build_ddi_fixtures.py from data/rules/ddi.yaml. "
            "Positives prove the matcher finds table rows; they do not prove the "
            "table is clinically complete (see docs/architecture/risk-list.md R-01)."
        ),
        "positives": positives,
        "negatives": negatives,
        "holes": holes,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="verify fixtures are current")
    args = parser.parse_args(argv)

    corpus = build()
    text = yaml.safe_dump(corpus, sort_keys=False, allow_unicode=True)

    if args.check:
        current = FIXTURE.read_text(encoding="utf-8") if FIXTURE.exists() else ""
        if current != text:
            print("FAIL: ddi_pairs.yaml is stale; run scripts/build_ddi_fixtures.py", file=sys.stderr)
            return 1
        print(f"PASS: fixtures current ({len(corpus['positives'])} positives, {len(corpus['negatives'])} negatives)")
        return 0

    FIXTURE.parent.mkdir(parents=True, exist_ok=True)
    FIXTURE.write_text(text, encoding="utf-8")
    print(
        f"wrote {FIXTURE.relative_to(ROOT)}: "
        f"{len(corpus['positives'])} positives, {len(corpus['negatives'])} negatives, "
        f"{len(corpus['holes'])} holes"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
